CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    unit_price NUMERIC(19, 2) NOT NULL,
    stock INTEGER NOT NULL,
    CONSTRAINT ck_product_unit_price_positive CHECK (unit_price > 0),
    CONSTRAINT ck_product_stock_non_negative CHECK (stock >= 0)
);

CREATE TABLE carts (
    id UUID PRIMARY KEY,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_cart_status CHECK (status IN ('OPEN', 'CHECKED_OUT'))
);

CREATE TABLE cart_items (
    cart_id UUID NOT NULL,
    product_id BIGINT NOT NULL,
    quantity INTEGER NOT NULL,
    PRIMARY KEY (cart_id, product_id),
    CONSTRAINT fk_cart_item_cart FOREIGN KEY (cart_id) REFERENCES carts (id),
    CONSTRAINT fk_cart_item_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT ck_cart_item_quantity_positive CHECK (quantity > 0)
);

CREATE TABLE orders (
    id UUID PRIMARY KEY,
    cart_id UUID NOT NULL,
    status VARCHAR(20) NOT NULL,
    gross NUMERIC(19, 2) NOT NULL,
    discount NUMERIC(19, 2) NOT NULL,
    net NUMERIC(19, 2) NOT NULL,
    coupon_code VARCHAR(64),
    discount_percent NUMERIC(5, 2),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_order_cart_id UNIQUE (cart_id),
    CONSTRAINT fk_order_cart FOREIGN KEY (cart_id) REFERENCES carts (id),
    CONSTRAINT ck_order_status CHECK (status = 'PLACED'),
    CONSTRAINT ck_order_amounts_non_negative CHECK (gross >= 0 AND discount >= 0 AND net >= 0),
    CONSTRAINT ck_order_discount_not_over_gross CHECK (discount <= gross),
    CONSTRAINT ck_order_net_reconciles CHECK (net = gross - discount)
);

CREATE TABLE order_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id UUID NOT NULL,
    product_id BIGINT NOT NULL,
    product_name VARCHAR(255) NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price NUMERIC(19, 2) NOT NULL,
    line_subtotal NUMERIC(19, 2) NOT NULL,
    CONSTRAINT fk_order_line_order FOREIGN KEY (order_id) REFERENCES orders (id),
    CONSTRAINT ck_order_line_quantity_positive CHECK (quantity > 0),
    CONSTRAINT ck_order_line_unit_price_non_negative CHECK (unit_price >= 0),
    CONSTRAINT ck_order_line_subtotal_non_negative CHECK (line_subtotal >= 0)
);

CREATE TABLE coupons (
    code VARCHAR(64) PRIMARY KEY,
    milestone INTEGER NOT NULL,
    discount_percent NUMERIC(5, 2) NOT NULL,
    status VARCHAR(20) NOT NULL,
    redeemed_order_id UUID,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_coupon_milestone UNIQUE (milestone),
    CONSTRAINT fk_coupon_redeemed_order FOREIGN KEY (redeemed_order_id) REFERENCES orders (id),
    CONSTRAINT ck_coupon_milestone_positive CHECK (milestone > 0),
    CONSTRAINT ck_coupon_discount_percent CHECK (discount_percent > 0 AND discount_percent <= 100),
    CONSTRAINT ck_coupon_status CHECK (status IN ('AVAILABLE', 'REDEEMED')),
    CONSTRAINT ck_coupon_redemption_consistent CHECK (
        (status = 'AVAILABLE' AND redeemed_order_id IS NULL)
        OR (status = 'REDEEMED' AND redeemed_order_id IS NOT NULL)
    )
);

CREATE TABLE idempotency_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id UUID NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    request_hash CHAR(64) NOT NULL,
    order_id UUID,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_idempotency_cart_key UNIQUE (cart_id, idempotency_key),
    CONSTRAINT fk_idempotency_cart FOREIGN KEY (cart_id) REFERENCES carts (id),
    CONSTRAINT fk_idempotency_order FOREIGN KEY (order_id) REFERENCES orders (id)
);
